/**
 * Get country name by enum value
 * @param {number} value - The enum value (0-196)
 * @returns {string} The country name or "Unknown"
 */
export const getCountryName = (value) => {
  return countries[value] || "Unknown";
};

/**
 * Get country enum value by name
 * @param {string} name - The country name
 * @returns {number|null} The enum value or null if not found
 */
export const getCountryValue = (name) => {
  const entry = Object.entries(countries).find(([, val]) => val === name);
  return entry ? parseInt(entry[0]) : null;
};

/**
 * Get all countries as array of objects for dropdowns
 * @returns {Array<{id: number, name: string}>}
 */
export const getCountriesArray = () => {
  return Object.entries(countries).map(([id, name]) => ({
    id: parseInt(id),
    name: name
  }));
};
